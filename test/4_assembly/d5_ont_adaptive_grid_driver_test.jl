    Test.@testset "S(k): error-free, canonical, positional" begin
        ref = dna("ACGTTGCAAGGCTTACCGATCGGATCCAGT")
        k = 7
        n_pos = length(ref) - k + 1
        exact = D5OntAdaptiveGridDriver.kmer_survival([ref], [ref], k)
        Test.@test exact.S == 1.0
        Test.@test exact.n_ref_positions == n_pos
        # Reads from the opposite strand observe every position (canonical k-mers).
        rc = D5OntAdaptiveGridDriver.kmer_survival(
            [BioSequences.reverse_complement(ref)], [ref], k)
        Test.@test rc.S == 1.0
        # One substitution at position p removes exactly the k windows covering it
        # (this reference has no other copy of those k-mers).
        p = 15
        mutated = copy(ref)
        mutated[p] = mutated[p] == BioSequences.DNA_A ? BioSequences.DNA_C :
                     BioSequences.DNA_A
        one_sub = D5OntAdaptiveGridDriver.kmer_survival([mutated], [ref], k)
        Test.@test one_sub.n_ref_positions_observed == n_pos - k
        Test.@test one_sub.S ≈ (n_pos - k) / n_pos
        # No reads: nothing observed, histogram empty, surrogate undefined.
        none = D5OntAdaptiveGridDriver.kmer_survival(BioSequences.LongDNA{4}[], [ref], k)
        Test.@test none.S == 0.0
        Test.@test none.s_hat_status == "undefined" && none.S_hat === nothing
        # Multiplicity histogram counts DISTINCT k-mers per exact multiplicity.
        # The fixture's windows at 16 (CCGATCG) and 17 (CGATCGG) are reverse
        # complements, i.e. ONE canonical k-mer: 24 positions, 23 distinct, and
        # that one is seen 4 times across two copies of the reference.
        twice = D5OntAdaptiveGridDriver.kmer_survival([ref, ref], [ref], k)
        Test.@test twice.n_distinct_read_kmers == 23
        Test.@test twice.histogram == Dict(2 => 22, 4 => 1)
        # The full ladder reaches k = 101 (Kmers.jl, not the assembler's cap).
        long_ref = dna(repeat("ACGTTGCAAGGCTTACCGATCGGATCCAGTTAGC", 5))
        ladder = D5OntAdaptiveGridDriver.survival_ladder([long_ref], [long_ref])
        Test.@test length(ladder) == 23
        Test.@test [r.k for r in ladder] ==
                   collect(D5OntAdaptiveGridDriver.D5OntAdaptiveGridAxes.D5_CANDIDATE_LADDER)
        Test.@test all(r -> r.S == 1.0, ladder)
    end

