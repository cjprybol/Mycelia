    Test.@testset "k* lookup: largest admissible rung, NoFeasibleK, collision floor" begin
        ladder = D5OntAdaptiveGridDriver.D5OntAdaptiveGridAxes.D5_CANDIDATE_LADDER
        Test.@test D5OntAdaptiveGridDriver.collision_floor_k(48_502) == 12   # Lambda
        Test.@test D5OntAdaptiveGridDriver.collision_floor_k(168_903) == 13  # T4
        # Survival falling with k: admissible set is a prefix; k* is its maximum.
        S = [1.0 - 0.04 * i for i in eachindex(ladder)]
        pick = D5OntAdaptiveGridDriver.select_k_star(S, 0.70; genome_size = 48_502)
        Test.@test pick.reason == "admissible"
        Test.@test pick.k_star ==
                   maximum(ladder[i] for i in eachindex(ladder) if S[i] >= 0.70)
        # Non-monotone input still returns the LARGEST rung meeting tau.
        bumpy = fill(0.1, length(ladder))
        bumpy[3] = 0.9
        bumpy[end] = 0.9
        Test.@test D5OntAdaptiveGridDriver.select_k_star(bumpy, 0.5;
            genome_size = 48_502).k_star == last(ladder)
        # Nothing meets tau: NoFeasibleK, never a fallback rung.
        none = D5OntAdaptiveGridDriver.select_k_star(fill(0.2, length(ladder)), 0.9;
            genome_size = 48_502)
        Test.@test none.k_star === D5OntAdaptiveGridDriver.NO_FEASIBLE_K
        Test.@test none.reason == "no_rung_meets_threshold"
        # Undefined S_hat rungs are dropped, not treated as zero or one.
        with_gaps = Any[nothing for _ in ladder]
        with_gaps[2] = 0.95
        Test.@test D5OntAdaptiveGridDriver.select_k_star(with_gaps, 0.9;
            genome_size = 48_502).k_star == ladder[2]
        # A genome so large the floor clears every rung.
        # The floor is INCLUSIVE: T4's floor is exactly 13, the ladder minimum.
        only13 = [k == 13 ? 0.9 : 0.1 for k in ladder]
        Test.@test D5OntAdaptiveGridDriver.select_k_star(only13, 0.5;
            genome_size = 168_903).k_star == 13
        # A floor INSIDE the ladder excludes the rungs below it (G = 5e9 -> floor 20):
        # survival meeting tau only at 13..19 is not admissible, even though a
        # floor-blind lookup would return 19.
        Test.@test D5OntAdaptiveGridDriver.collision_floor_k(5_000_000_000) == 20
        low_only = [k <= 19 ? 0.9 : 0.1 for k in ladder]
        Test.@test D5OntAdaptiveGridDriver.select_k_star(low_only, 0.5;
            genome_size = 5_000_000_000).reason == "no_rung_meets_threshold"
        to21 = [k <= 21 ? 0.9 : 0.1 for k in ladder]
        Test.@test D5OntAdaptiveGridDriver.select_k_star(to21, 0.5;
            genome_size = 5_000_000_000).k_star == 21
        huge = D5OntAdaptiveGridDriver.select_k_star(ones(length(ladder)), 0.5;
            genome_size = big(10)^62)
        Test.@test huge.k_star === D5OntAdaptiveGridDriver.NO_FEASIBLE_K
        Test.@test huge.reason == "no_rung_above_collision_floor"
        msg = error_message(() -> D5OntAdaptiveGridDriver.select_k_star([1.0], 0.5;
            genome_size = 48_502))
        Test.@test msg !== nothing && occursin("23-rung ladder", msg)
    end

    Test.@testset "Phase B plan: reuse, assemble, infeasible, NoFeasibleK" begin
        ladder = collect(D5OntAdaptiveGridDriver.D5OntAdaptiveGridAxes.D5_CANDIDATE_LADDER)
        rows_for(S;
            S_hat = S) = [Dict{String, Any}("k" => k, "S" => s, "S_hat" => h)
                          for (k, s, h) in zip(ladder, S, S_hat)]
        adaptive = first(filter(c -> c.technology === :ont && c.k_policy === :adaptive,
            D5OntAdaptiveGridDriver.ont_cells()))
        # S drops below 0.5 after rung 21 -> k* = 21, a comparator rung -> reuse.
        S = [k <= 21 ? 0.9 : 0.1 for k in ladder]
        plan = D5OntAdaptiveGridDriver.phase_b_plan(adaptive, rows_for(S), 0.5, 0.5;
            genome_size = 48_502)
        Test.@test plan.action === :reuse && plan.k_star == 21
        Test.@test plan.reuse_cell_id ==
                   D5OntAdaptiveGridDriver.cell_id(merge(adaptive, (; k_policy = 21)))
        Test.@test plan.reuse_cell_id in D5OntAdaptiveGridDriver.cell_id.(D5OntAdaptiveGridDriver.phase_a_cells())
        # k* = 29 is not a comparator rung -> a new assembly.
        S29 = [k <= 29 ? 0.9 : 0.1 for k in ladder]
        Test.@test D5OntAdaptiveGridDriver.phase_b_plan(adaptive, rows_for(S29), 0.5, 0.5;
            genome_size = 48_502).action === :assemble
        # k* = 101 is beyond the assembler's cap -> infeasible, not a fallback.
        high = D5OntAdaptiveGridDriver.phase_b_plan(adaptive, rows_for(fill(0.9, 23)),
            0.5, 0.5; genome_size = 48_502)
        Test.@test high.action === :infeasible && high.k_star == 101
        # Nothing meets tau -> NoFeasibleK.
        none = D5OntAdaptiveGridDriver.phase_b_plan(adaptive, rows_for(fill(0.1, 23)),
            0.5, 0.5; genome_size = 48_502)
        Test.@test none.action === :no_feasible_k
        Test.@test none.k_star === D5OntAdaptiveGridDriver.NO_FEASIBLE_K
        # S_hat feeds only k_star_hat, through its own threshold; undefined rungs drop.
        S_hat = Any[k == 15 ? 0.7 : nothing for k in ladder]
        mixed = D5OntAdaptiveGridDriver.phase_b_plan(adaptive, rows_for(S; S_hat), 0.5,
            0.6; genome_size = 48_502)
        Test.@test mixed.k_star == 21 && mixed.k_star_hat == 15
        # tau and tau_hat are NOT interchangeable: with tau=0.5, tau_hat=0.8 the S
        # lookup gives 21 and S_hat (0.7 at 15) meets nothing; swapping the two
        # thresholds would give 21 and 15.
        split = D5OntAdaptiveGridDriver.phase_b_plan(adaptive, rows_for(S; S_hat), 0.5,
            0.8; genome_size = 48_502)
        Test.@test split.k_star == 21
        Test.@test split.k_star_hat === D5OntAdaptiveGridDriver.NO_FEASIBLE_K
        # Rows out of ladder order would pair S with the wrong k: refused.
        msg = error_message(() -> D5OntAdaptiveGridDriver.phase_b_plan(adaptive,
            reverse(rows_for(S)), 0.5, 0.5; genome_size = 48_502))
        Test.@test msg !== nothing && occursin("in order", msg)
        fixed = first(D5OntAdaptiveGridDriver.phase_a_cells())
        msg = error_message(() -> D5OntAdaptiveGridDriver.phase_b_plan(fixed,
            rows_for(S), 0.5, 0.5; genome_size = 48_502))
        Test.@test msg !== nothing && occursin("is for :adaptive cells", msg)
        msg = error_message(() -> D5OntAdaptiveGridDriver.phase_b_plan(adaptive,
            rows_for(S)[1:22], 0.5, 0.5; genome_size = 48_502))
        Test.@test msg !== nothing && occursin("23-rung ladder", msg)
        Test.@test first(D5OntAdaptiveGridDriver.cell_row_columns()) == "cell_id"
        Test.@test "NGA50" in D5OntAdaptiveGridDriver.cell_row_columns()
    end

